-- README tables "timeDeposits" / "withdrawals" with camelCase columns, mapped to idiomatic PostgreSQL snake_case
-- (unquoted identifiers are case-folded by PostgreSQL; snake_case is also Hibernate's default naming).
CREATE TABLE time_deposits
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_type VARCHAR(50)    NOT NULL, -- no CHECK constraint: unknown plan types must load and earn no interest
    days      INTEGER        NOT NULL,
    balance   NUMERIC(19, 2) NOT NULL
);

CREATE TABLE withdrawals
(
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER        NOT NULL REFERENCES time_deposits (id),
    amount          NUMERIC(19, 2) NOT NULL,
    date            DATE           NOT NULL
);

CREATE INDEX idx_withdrawals_time_deposit_id ON withdrawals (time_deposit_id);
